#!/usr/bin/env bash
# make seal — the one-way door. Writes .env.sealed, installs the .pth egress-guard
# bootstrap into site-packages, then performs the GATED PROVISION->OPERATE
# transition (refuses unless the invariant-13 preconditions hold: manifest
# full-verify + valid signature + a green online negative control). Prints the
# physical disconnect checklist. Idempotent except that each seal increments
# seal_generation.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PY="$ROOT/.venv/bin/python"
SITE="$ROOT/.venv/lib/python3.11/site-packages"

# 1) .env.sealed — sourced by bin/sagp-serve BEFORE the interpreter starts, so
#    HF_HUB_OFFLINE et al. take effect before huggingface_hub is imported.
#    Single-quoted heredoc: $PWD is written literally and expands at source time.
cat > "$ROOT/.env.sealed" <<'ENVEOF'
# GENERATED by `make seal` — do not hand-edit. Sourced by bin/sagp-serve.
export HF_HUB_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1 HF_HUB_DISABLE_IMPLICIT_TOKEN=1
export HF_HUB_DISABLE_UPDATE_CHECK=1 HF_HUB_DISABLE_XET=1 DO_NOT_TRACK=1
export HF_HOME="$PWD/models/hf-home"
export TLDEXTRACT_CACHE="$PWD/models/tldextract"
export TOKENIZERS_PARALLELISM=false PYTHONDONTWRITEBYTECODE=1
export OLLAMA_HOST=127.0.0.1:11434
export OLLAMA_MODELS="$PWD/models/ollama"
export OLLAMA_NO_CLOUD=1 OLLAMA_NOPRUNE=1 OLLAMA_ORIGINS=http://127.0.0.1
export OLLAMA_MAX_LOADED_MODELS=1 OLLAMA_NUM_PARALLEL=1 OLLAMA_MAX_QUEUE=16
export OLLAMA_CONTEXT_LENGTH=4096 OLLAMA_KEEP_ALIVE=30m
export OLLAMA_FLASH_ATTENTION=1 OLLAMA_KV_CACHE_TYPE=q8_0
export no_proxy='*' NO_PROXY='*'
unset  http_proxy https_proxy all_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY
export SAGP_ENV=prod
ENVEOF
chmod 600 "$ROOT/.env.sealed"
echo "seal: wrote .env.sealed (0600)"

# 2) Install the .pth bootstrap. A .pth line beginning with `import` runs at
#    interpreter start, arming the egress guard for the whole process. The mode is
#    read from .airgap/state.json (PROVISION -> not armed), never an env var.
if [[ ! -d "$SITE" ]]; then
  echo "seal: site-packages not found at $SITE — run 'make venvs' first." >&2
  exit 1
fi
cp "$ROOT/airgap_guard_boot.py" "$SITE/airgap_guard_boot.py"
echo "import airgap_guard_boot" > "$SITE/airgap_guard.pth"
echo "seal: installed airgap_guard.pth + airgap_guard_boot.py into site-packages"

# 3) The gated one-way-door transition (exits non-zero if a precondition is unmet).
"$PY" -m sagp.netguard.phase seal

# 4) The physical disconnect checklist — the part software cannot do for you.
cat <<'MSG'

Now physically disconnect and confirm the air gap:
  networksetup -setairportpower en0 off          # Wi-Fi off
  # unplug any Ethernet / Thunderbolt network adapters
  ping -c1 1.1.1.1                                # MUST fail
  curl -sS --max-time 3 https://huggingface.co   # MUST fail
Then:  make ollama-up && make serve && make proof
MSG
