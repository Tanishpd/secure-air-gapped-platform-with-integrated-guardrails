"""Runtime settings.

``Settings`` is the single typed view of every ``SAGP_``-prefixed knob: caps,
timeouts, model/profile selection, filesystem paths, and the runtime secrets.

Two rules this module obeys:

* **It imports nothing from ``sagp.*``** — it is the base of the dependency
  graph (CLAUDE.md §7). Validation failures raise pydantic's ``ValidationError``;
  the app's lifespan converts that into a boot refusal.
* **Thresholds do not live here.** Detector thresholds are data in
  ``config/guardrails.yaml`` / ``config/entities.yaml`` (invariant 12), so a
  decision can be replayed against the policy hash that produced it. This file
  carries only caps, timeouts, paths and profile selection.

``extra="forbid"`` means a mistyped ``SAGP_`` variable refuses to boot rather
than silently defaulting.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Literal

from pydantic import Field, SecretStr, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="SAGP_",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="forbid",
        frozen=True,
    )

    # --- environment / profile ---------------------------------------------
    env: Literal["dev", "prod"] = "dev"
    # SAGP_GUARD is honoured only by the verify-online harness while phase==PROVISION.
    # In OPERATE the .pth guard derives its mode from .airgap/state.json, not this
    # field (BLUEPRINT §6); anything other than "enforce" there is invalidating.
    guard: Literal["enforce", "audit"] = "enforce"

    # --- model / backend selection -----------------------------------------
    llm_model: str = "llama3.2:3b-instruct-q4_K_M"
    spacy_model: Literal["en_core_web_sm", "en_core_web_md", "en_core_web_lg"] = "en_core_web_md"
    qdrant_mode: Literal["embedded", "server", ":memory:"] = "embedded"
    rehydrate_output: bool = False

    # --- caps (BLUEPRINT §12) ----------------------------------------------
    max_input_chars: int = Field(8000, gt=0)
    max_scan_unit_chars: int = Field(20_000, gt=0)
    max_doc_bytes: int = Field(52_428_800, gt=0)
    max_windows: int = Field(16, gt=0)
    max_ctx_chars: int = Field(7000, gt=0)
    max_vault_entries: int = Field(2000, gt=0)
    # Per-principal fixed-window rate limit (C0). Over the limit -> 429 RateLimited.
    rate_limit_per_min: int = Field(60, gt=0)

    # --- timeouts (BLUEPRINT §12) ------------------------------------------
    timeout_injection_ms: int = Field(2000, gt=0)
    timeout_pii_ms: int = Field(3000, gt=0)
    timeout_embed_ms: int = Field(2000, gt=0)
    timeout_retrieve_ms: int = Field(3000, gt=0)
    timeout_llm_s: int = Field(120, gt=0)
    timeout_request_s: int = Field(180, gt=0)
    # Placeholder; calibrated above the slowest detector path at M13 (GUARDRAILS §1).
    rejection_deadline_ms: int = Field(120, gt=0)

    # --- filesystem paths (resolved relative to CWD = repo root) ------------
    data_dir: Path = Path("data")
    models_dir: Path = Path("models")
    audit_dir: Path = Path("audit")
    config_dir: Path = Path("config")

    # --- secrets (generated by 09_secrets.py into .env; None in dev) --------
    api_token: SecretStr | None = None
    api_token_reveal: SecretStr | None = None
    audit_hmac_key: SecretStr | None = None
    pii_pepper: SecretStr | None = None

    @model_validator(mode="after")
    def _forbid_unknown_sagp_env(self) -> Settings:
        """Refuse to boot on a mistyped ``SAGP_`` process-env variable (invariant 12).

        ``extra="forbid"`` catches typos in a ``.env`` file, but the env source
        does field→variable lookup and never sees an unknown ``SAGP_`` var in the
        process environment — and the app is launched with exported env vars. So
        we enumerate them here: any ``SAGP_``-prefixed variable that matches no
        field is a typo, and a typo must fail loudly, not default silently.
        """
        known = {f"SAGP_{name.upper()}" for name in type(self).model_fields}
        unknown = sorted(
            k for k in os.environ if k.upper().startswith("SAGP_") and k.upper() not in known
        )
        if unknown:
            raise ValueError(f"unknown SAGP_ setting(s) — typo? {', '.join(unknown)}")
        return self

    @property
    def qdrant_path(self) -> Path:
        """Local segment directory for the embedded Qdrant backend."""
        return self.data_dir / "qdrant"


def load_settings() -> Settings:
    """Build a Settings instance from the environment and ``.env``.

    Kept as a function (not a module-level singleton) so import of ``sagp`` has
    no side effects and tests can construct settings with a controlled
    environment. The app wires a single cached instance in ``app/deps.py``.
    """
    return Settings()
